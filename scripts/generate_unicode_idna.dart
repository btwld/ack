#!/usr/bin/env dart

import 'dart:io';

/// Generates the IDNA2008 repertoire from IANA's complete Unicode 12 registry.
/// See packages/ack/lib/src/json_schema/IDNA_DATA.md for pinned sources.
void main(List<String> args) {
  if (args.length != 2) {
    stderr.writeln(
      'Usage: dart scripts/generate_unicode_idna.dart '
      '<idna-tables-properties.csv> <DerivedGeneralCategory.txt>',
    );
    exitCode = 64;
    return;
  }
  try {
    final csv = File(args[0]).readAsLinesSync();
    final categories = File(args[1]).readAsStringSync();
    if (csv.isEmpty ||
        !csv.first.startsWith('Codepoint,Property,') ||
        !categories.startsWith('# DerivedGeneralCategory-12.0.0.txt')) {
      throw const FormatException('Expected IANA and Unicode 12.0.0 data.');
    }
    const properties = {
      'PVALID': 'pvalid',
      'CONTEXTJ': 'contextj',
      'CONTEXTO': 'contexto',
      'DISALLOWED': 'disallowed',
      'UNASSIGNED': 'disallowed',
    };
    final output = StringBuffer(
      '''// Generated by scripts/generate_unicode_idna.dart; do not edit.
// RFC 5892 / IANA IDNA2008 derived properties, Unicode 12.0.0.
// Source: https://www.iana.org/assignments/idna-tables-12.0.0/
// Unicode data: https://www.unicode.org/Public/12.0.0/ucd/extracted/
// Copyright © 2019 Unicode, Inc. See UNICODE_LICENSE in this directory.
part of '../schemas/schema.dart';

enum _IdnaProperty { pvalid, contextj, contexto, disallowed }

_IdnaProperty _idnaProperty(int rune) {
  var low = 0;
  var high = _idnaRanges.length - 1;
  while (low <= high) {
    final middle = (low + high) ~/ 2;
    final (start, end, property) = _idnaRanges[middle];
    if (rune < start) {
      high = middle - 1;
    } else if (rune > end) {
      low = middle + 1;
    } else {
      return property;
    }
  }
  return _IdnaProperty.disallowed;
}

// DISALLOWED and UNASSIGNED are rejected; store only admissible intervals.
const _idnaRanges = <(int, int, _IdnaProperty)>[
''',
    );
    var next = 0;
    for (final line in csv.skip(1).where((line) => line.trim().isNotEmpty)) {
      final fields = line.split(',');
      final bounds = fields[0].split('-');
      final start = int.parse(bounds[0], radix: 16);
      final end = int.parse(bounds.last, radix: 16);
      final property = properties[fields[1]];
      if (start != next || end < start || property == null) {
        throw FormatException('Invalid or incomplete IANA range: $line');
      }
      next = end + 1;
      if (property != 'disallowed') {
        output.writeln(
          '  (0x${start.toRadixString(16)}, 0x${end.toRadixString(16)}, '
          '_IdnaProperty.$property),',
        );
      }
    }
    if (next != 0x110000) {
      throw const FormatException(
        'IANA data must cover all Unicode code points.',
      );
    }
    output.writeln('];\n\nbool _isIdnaMark(int rune) =>');
    final marks = <(int, int)>[];
    final pattern = RegExp(
      r'^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*; (M[nce])\b',
      multiLine: true,
    );
    for (final match in pattern.allMatches(categories)) {
      marks.add((
        int.parse(match[1]!, radix: 16),
        int.parse(match[2] ?? match[1]!, radix: 16),
      ));
    }
    marks.sort((a, b) => a.$1.compareTo(b.$1));
    // A label's first code point must not be a mark (RFC 5891 section 4.2.3.2).
    // This uses the same pinned UCD, independently of the VM/JS regex version.
    output.writeln(
      '    _idnaMarkRanges.any((range) => rune >= range.\$1 && rune <= range.\$2);',
    );
    output.writeln('const _idnaMarkRanges = <(int, int)>[');
    for (final (start, end) in marks) {
      output.writeln(
        '  (0x${start.toRadixString(16)}, 0x${end.toRadixString(16)}),',
      );
    }
    output.writeln('];');
    const path = 'packages/ack/lib/src/json_schema/unicode_idna.dart';
    File(path).writeAsStringSync(output.toString());
    final result = Process.runSync(Platform.resolvedExecutable, [
      'format',
      path,
    ]);
    stdout.write(result.stdout);
    stderr.write(result.stderr);
    exitCode = result.exitCode;
  } on FileSystemException catch (error) {
    stderr.writeln('Cannot read/write IDNA data: $error');
    exitCode = 66;
  } on FormatException catch (error) {
    stderr.writeln('Invalid IDNA data: $error');
    exitCode = 65;
  }
}
