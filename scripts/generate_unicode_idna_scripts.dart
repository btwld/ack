#!/usr/bin/env dart

import 'dart:io';

/// Generates the Script lookup used by RFC 5892 Appendix A.4-A.7.
void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln(
      'Usage: dart scripts/generate_unicode_idna_scripts.dart <Scripts.txt>\n'
      'Source: https://www.unicode.org/Public/12.0.0/ucd/Scripts.txt',
    );
    exitCode = 64;
    return;
  }
  final String input;
  try {
    input = File(args.single).readAsStringSync();
  } on FileSystemException catch (error) {
    stderr.writeln('Cannot read Unicode data: $error');
    exitCode = 66;
    return;
  }
  if (!input.startsWith('# Scripts-12.0.0.txt')) {
    stderr.writeln('Expected Unicode 12.0.0 Scripts.txt.');
    exitCode = 65;
    return;
  }
  const scripts = {'Greek', 'Hebrew', 'Hiragana', 'Katakana', 'Han'};
  final ranges = <(int, int, String)>[];
  final pattern = RegExp(
    r'^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*; (\w+)',
    multiLine: true,
  );
  for (final match in pattern.allMatches(input)) {
    final script = match[3]!;
    if (!scripts.contains(script)) continue;
    ranges.add((
      int.parse(match[1]!, radix: 16),
      int.parse(match[2] ?? match[1]!, radix: 16),
      script.toLowerCase(),
    ));
  }
  ranges.sort((a, b) => a.$1.compareTo(b.$1));
  final output = StringBuffer(
    '''// Generated by scripts/generate_unicode_idna_scripts.dart; do not edit.
// Unicode 12.0.0 Script (not Script_Extensions).
// Source: https://www.unicode.org/Public/12.0.0/ucd/Scripts.txt
// Copyright © 2019 Unicode, Inc. See UNICODE_LICENSE in this directory.
part of '../schemas/schema.dart';

enum _IdnaScript { other, greek, hebrew, hiragana, katakana, han }

_IdnaScript _idnaScript(int rune) {
  var low = 0;
  var high = _idnaScriptRanges.length - 1;
  while (low <= high) {
    final middle = (low + high) ~/ 2;
    final (start, end, script) = _idnaScriptRanges[middle];
    if (rune < start) {
      high = middle - 1;
    } else if (rune > end) {
      low = middle + 1;
    } else {
      return script;
    }
  }
  return _IdnaScript.other;
}

// All scripts outside the five contextual Script values return other.
// In particular, Common and Inherited do not satisfy the Japanese rule.
const _idnaScriptRanges = <(int, int, _IdnaScript)>[
''',
  );
  for (final (start, end, script) in ranges) {
    output.writeln(
      '  (0x${start.toRadixString(16)}, 0x${end.toRadixString(16)}, '
      '_IdnaScript.$script),',
    );
  }
  output.writeln('];');
  const path = 'packages/ack/lib/src/json_schema/unicode_idna_scripts.dart';
  File(path).writeAsStringSync(output.toString());
  final result = Process.runSync(Platform.resolvedExecutable, ['format', path]);
  stdout.write(result.stdout);
  stderr.write(result.stderr);
  exitCode = result.exitCode;
}
