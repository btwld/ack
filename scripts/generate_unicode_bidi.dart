#!/usr/bin/env dart

import 'dart:io';

/// Regenerates the private Unicode Bidi_Class lookup from Unicode 17.0.0.
/// Run from the repository root with the downloaded DerivedBidiClass.txt path.
void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln(
      'Usage: dart scripts/generate_unicode_bidi.dart <DerivedBidiClass.txt>\n'
      'Source: https://www.unicode.org/Public/17.0.0/ucd/extracted/'
      'DerivedBidiClass.txt',
    );
    exitCode = 64;
    return;
  }
  final String input;
  try {
    input = File(args.single).readAsStringSync();
  } on FileSystemException catch (error) {
    stderr.writeln('Cannot read Unicode data: $error');
    exitCode = 66;
    return;
  }
  if (!input.startsWith('# DerivedBidiClass-17.0.0.txt')) {
    stderr.writeln('Expected Unicode 17.0.0 DerivedBidiClass.txt.');
    exitCode = 65;
    return;
  }
  const aliases = {
    'Left_To_Right': 'L',
    'Right_To_Left': 'R',
    'Arabic_Letter': 'AL',
    'European_Terminator': 'ET',
  };
  final classes = List.filled(0x110000, 'L');
  // Apply @missing defaults first, then explicit entries (UAX #44).
  for (final prefix in [r'# @missing: ', '^']) {
    final pattern = RegExp(
      '$prefix([0-9A-F]+)(?:\\.\\.([0-9A-F]+))?\\s*; (\\w+)',
      multiLine: true,
    );
    for (final match in pattern.allMatches(input)) {
      final start = int.parse(match[1]!, radix: 16);
      final end = int.parse(match[2] ?? match[1]!, radix: 16);
      final name = aliases[match[3]] ?? match[3]!;
      classes.fillRange(start, end + 1, name);
    }
  }
  const supported = {
    'L',
    'R',
    'AL',
    'EN',
    'AN',
    'ES',
    'CS',
    'ET',
    'ON',
    'BN',
    'NSM',
  };
  final output = StringBuffer(
    '''// Generated by scripts/generate_unicode_bidi.dart; do not edit.
// Unicode 17.0.0 Bidi_Class, including the UAX #44 @missing defaults.
// Source: https://www.unicode.org/Public/17.0.0/ucd/extracted/DerivedBidiClass.txt
// Copyright © 2025 Unicode, Inc. See UNICODE_LICENSE in this directory.
part of '../schemas/schema.dart';

enum _UnicodeBidiClass { l, r, al, en, an, es, cs, et, on, bn, nsm, disallowed }

_UnicodeBidiClass _unicodeBidiClass(int rune) {
  var low = 0;
  var high = _unicodeBidiRanges.length - 1;
  while (low <= high) {
    final middle = (low + high) ~/ 2;
    final (start, end, type) = _unicodeBidiRanges[middle];
    if (rune < start) {
      high = middle - 1;
    } else if (rune > end) {
      low = middle + 1;
    } else {
      return type;
    }
  }
  return _UnicodeBidiClass.l;
}

// L is the default; store only non-L intervals in code point order.
const _unicodeBidiRanges = <(int, int, _UnicodeBidiClass)>[
''',
  );
  for (var start = 0; start < classes.length;) {
    final type = classes[start];
    var end = start + 1;
    while (end < classes.length && classes[end] == type) {
      end++;
    }
    if (type != 'L') {
      final name = supported.contains(type) ? type.toLowerCase() : 'disallowed';
      output.writeln(
        '  (0x${start.toRadixString(16)}, 0x${(end - 1).toRadixString(16)}, '
        '_UnicodeBidiClass.$name),',
      );
    }
    start = end;
  }
  output.writeln('];');
  const path = 'packages/ack/lib/src/json_schema/unicode_bidi.dart';
  File(path).writeAsStringSync(output.toString());
  final format = Process.runSync(Platform.resolvedExecutable, ['format', path]);
  stdout.write(format.stdout);
  stderr.write(format.stderr);
  exitCode = format.exitCode;
}
