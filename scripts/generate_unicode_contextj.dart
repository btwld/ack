#!/usr/bin/env dart

import 'dart:io';

/// Regenerates RFC 5892 ContextJ property data from Unicode 17.0.0.
/// Run from the repository root with downloaded DerivedJoiningType.txt and
/// DerivedCombiningClass.txt paths (in that order).
void main(List<String> args) {
  if (args.length != 2) {
    stderr.writeln(
      'Usage: dart scripts/generate_unicode_contextj.dart '
      '<DerivedJoiningType.txt> <DerivedCombiningClass.txt>\n'
      'Sources: https://www.unicode.org/Public/17.0.0/ucd/extracted/',
    );
    exitCode = 64;
    return;
  }
  final List<String> inputs;
  try {
    inputs = args.map((path) => File(path).readAsStringSync()).toList();
  } on FileSystemException catch (error) {
    stderr.writeln('Cannot read Unicode data: $error');
    exitCode = 66;
    return;
  }
  if (!inputs[0].startsWith('# DerivedJoiningType-17.0.0.txt') ||
      !inputs[1].startsWith('# DerivedCombiningClass-17.0.0.txt')) {
    stderr.writeln('Expected Unicode 17.0.0 joining and combining class data.');
    exitCode = 65;
    return;
  }
  final pattern = RegExp(
    r'^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*; (\w+)',
    multiLine: true,
  );
  // U is the UAX #44 @missing default in DerivedJoiningType.txt. The derived
  // file includes every T character, including those absent in ArabicShaping.
  final joiningTypes = List.filled(0x110000, 'U');
  for (final match in pattern.allMatches(inputs[0])) {
    final start = int.parse(match[1]!, radix: 16);
    final end = int.parse(match[2] ?? match[1]!, radix: 16);
    joiningTypes.fillRange(start, end + 1, match[3]!);
  }
  final output = StringBuffer(
    '''// Generated by scripts/generate_unicode_contextj.dart; do not edit.
// Unicode 17.0.0 Joining_Type and Canonical_Combining_Class=Virama (9).
// Sources: https://www.unicode.org/Public/17.0.0/ucd/extracted/
//          DerivedJoiningType.txt and DerivedCombiningClass.txt
// Copyright © 2025 Unicode, Inc. See UNICODE_LICENSE in this directory.
part of '../schemas/schema.dart';

enum _UnicodeJoiningType { u, c, d, l, r, t }

_UnicodeJoiningType _unicodeJoiningType(int rune) {
  var low = 0;
  var high = _unicodeJoiningRanges.length - 1;
  while (low <= high) {
    final middle = (low + high) ~/ 2;
    final (start, end, type) = _unicodeJoiningRanges[middle];
    if (rune < start) {
      high = middle - 1;
    } else if (rune > end) {
      low = middle + 1;
    } else {
      return type;
    }
  }
  return _UnicodeJoiningType.u;
}

// U is the default; store only non-U intervals in code point order.
const _unicodeJoiningRanges = <(int, int, _UnicodeJoiningType)>[
''',
  );
  for (var start = 0; start < joiningTypes.length;) {
    final type = joiningTypes[start];
    var end = start + 1;
    while (end < joiningTypes.length && joiningTypes[end] == type) {
      end++;
    }
    if (type != 'U') {
      output.writeln(
        '  (0x${start.toRadixString(16)}, 0x${(end - 1).toRadixString(16)}, '
        '_UnicodeJoiningType.${type.toLowerCase()}),',
      );
    }
    start = end;
  }
  output.writeln('];\n\nbool _isVirama(int rune) => const {');
  for (final match in pattern.allMatches(inputs[1])) {
    if (match[3] != '9') continue;
    final start = int.parse(match[1]!, radix: 16);
    final end = int.parse(match[2] ?? match[1]!, radix: 16);
    for (var rune = start; rune <= end; rune++) {
      output.writeln('  0x${rune.toRadixString(16)},');
    }
  }
  output.writeln('}.contains(rune);');
  const path = 'packages/ack/lib/src/json_schema/unicode_contextj.dart';
  File(path).writeAsStringSync(output.toString());
  final format = Process.runSync(Platform.resolvedExecutable, ['format', path]);
  stdout.write(format.stdout);
  stderr.write(format.stderr);
  exitCode = format.exitCode;
}
